const fs=require('fs'),assert=require('assert/strict');
const puppeteer=require('/home/reidsurmeier/promo-lab/node_modules/puppeteer-core');
const wait=ms=>new Promise(r=>setTimeout(r,ms));
(async()=>{
 const [url,out]=process.argv.slice(2);fs.mkdirSync(out,{recursive:true});
 const browser=await puppeteer.launch({executablePath:'/usr/bin/google-chrome',headless:true,protocolTimeout:300000,args:['--no-sandbox','--use-angle=swiftshader','--enable-unsafe-swiftshader']});
 try{
  const page=await browser.newPage(),errors=[],records={url};
  await page.setViewport({width:800,height:600});
  page.on('pageerror',e=>{errors.push(String(e));console.log(String(e))});
  page.on('console',m=>{if(m.type()==='error'&&!/404|2D MSAA|render_target_set_msaa/.test(m.text())){errors.push(m.text());console.log(m.text())}});
  await page.goto(url+'?qa-crt=1&render_qa=1',{waitUntil:'domcontentloaded',timeout:120000});
  await page.waitForFunction(()=>window.galleryRenderCommand&&window.shellCrtQa?.shell.active===4&&!window.shellCrtQa.shell.switching&&!document.getElementById('status'),{timeout:240000});
  console.log('Collection loaded');
  const command=action=>page.evaluate(action=>window.galleryRenderCommand(JSON.stringify(action)),action);
  const state=async()=>{await command({action:'state'});return page.evaluate(()=>window.galleryRenderState)};
  const xy=async point=>page.evaluate(point=>{const r=window.shellCrtQa.stage_rect;return[r[0]+point[0]*r[2],r[1]+point[1]*r[3]]},point);
  const click=async point=>page.mouse.click(...await xy(point));
  const pose=async scene=>{await command({action:'pose',scene});await command({action:'release'});await wait(400)};
  const preview=async open=>page.waitForFunction(open=>{window.galleryRenderCommand(JSON.stringify({action:'state'}));return !!window.galleryRenderState.preview.tag===open},{timeout:20000},open);
  const openPainting=async()=>{
   await pose('art');const s=await state();assert(s.visible_paintings.length);
   const r=s.display_rect_normalized,c=[(r[0]+r[2])/2,r[1]+(r[3]-r[1])*.2];
   const targets=s.visible_paintings.sort((a,b)=>Math.hypot(a.point[0]-c[0],a.point[1]-c[1])-Math.hypot(b.point[0]-c[0],b.point[1]-c[1]));
   await click(targets[0].point);await preview(true);await wait(400);
   const opened=await state();assert.equal(opened.preview.tag,targets[0].tag);assert.equal(opened.preview.outer_frame_visible,false);
   const p=opened.preview;assert(Math.abs(p.picture_size[0]/p.picture_size[1]-p.source_size[0]/p.source_size[1])<.001);
   return opened;
  };
  await pose('warm');records.normal=await state();
  const beforeStage=await page.evaluate(()=>window.shellCrtQa.stage_rect);
  await click([966/1080,27/1080]);await page.waitForFunction(()=>!!document.fullscreenElement,{timeout:5000});
  await page.setViewport({width:1600,height:1000});await wait(800);
  records.fullscreen=await state();
  const afterStage=await page.evaluate(()=>window.shellCrtQa.stage_rect);
  assert(afterStage[3]>beforeStage[3]);assert(Math.abs(records.fullscreen.container[0]/records.fullscreen.container[1]-2110/1412)<.01);
  await page.screenshot({path:out+'/fullscreen.png'});
  const opened=await openPainting();records.opened=opened;
  await page.screenshot({path:out+'/preview-fullscreen.png'});
  await page.mouse.move(...await xy([.5,.5]));await page.mouse.wheel({deltaY:-300});await wait(300);
  const zoomed=await state();assert(zoomed.preview.zoom>1);
  const center=await xy([.5,.5]);await page.mouse.move(...center);await page.mouse.down();await page.mouse.move(center[0]+80,center[1]+40,{steps:5});await page.mouse.up();await wait(200);
  const panned=await state();assert(Math.hypot(...panned.preview.pan.map((v,i)=>v-zoomed.preview.pan[i]))>10);
  await click(panned.preview.close);await preview(false);await wait(400);
  const returned=await state();records.returned=returned;assert(returned.preview.outer_frame_visible);assert.deepEqual(returned.position,opened.position);assert.deepEqual(returned.camera_transform,opened.camera_transform);
  await page.screenshot({path:out+'/returned-fullscreen.png'});
  await click([966/1080,27/1080]);await page.waitForFunction(()=>!document.fullscreenElement,{timeout:5000});
  await page.setViewport({width:1080,height:1080});await pose('warm');
  await page.screenshot({path:out+'/gameplay.png'});
  const before=await state();await page.keyboard.down('s');await wait(700);await page.keyboard.up('s');await wait(500);const stopped=await state();await wait(300);const still=await state();
  assert(Math.hypot(...before.position.map((v,i)=>v-stopped.position[i]))>.2);assert.deepEqual(still.position,stopped.position);assert.equal(before.camera_fov,stopped.camera_fov);assert.equal(stopped.visitor.identity,'Hair36');assert.equal(stopped.paintings,23);
  await page.setViewport({width:486,height:720});await wait(500);records.portrait=await openPainting();
  await page.screenshot({path:out+'/portrait-preview.png'});
  await page.keyboard.press('Escape');await preview(false);assert((await state()).preview.outer_frame_visible);
  await page.screenshot({path:out+'/portrait-returned.png'});
  assert.deepEqual(errors,[]);records.errors=errors;
  fs.writeFileSync(out+'/results.json',JSON.stringify(records,null,2));
  console.log('COLLECTION189 real artwork click/X/Escape, fullscreen/restore, proportional resize, zoom/pan, movement/release and 23 paintings PASS');
 }finally{await browser.close()}
})().catch(e=>{console.error(e);process.exitCode=1});
